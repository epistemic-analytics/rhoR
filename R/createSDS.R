###
#' @include set.R
#' @title Create Simulated Data Set
#' 
#' @description
#' Creates a simulated data \code{\link{set}} based off the given parameters
#' 
#' @param length the length of the simulated data set to be created
#' @param baserate the \code{\link{baserate}} of the simulated data set
#' @param kappaMin the minimum kappa of the simulated data set
#' @param kappaMax the maximum kappa of the simulated data set
#' @param precisionMin the minimum precision of the simulated data set
#' @param precisionMax the maximum precision of the simulated data set
#' 
#' @keywords set, create
#' 
#' @details
#' Sets are generated by first picking a random kappa within the range and a random precision within its range.  If the random kappa, random precision, and baserate are not mathematically possible, then the precision is resampled from a range of mathematically possible values.  A unique simulated data set is then constructed given these parameters.
#' 
#' @return returns a simulated data set that fulfills the given parameters
#' 
###

createSDS = function(length, baserate, kappaMin, kappaMax, precisionMin, precisionMax){
  return(createRandomSet(setLength = length, baserate = baserate, kappa = runif(1, kappaMin, kappaMax), minPrecision = precisionMin, maxPrecision = precisionMax))
}