###
#' @include set.R
#' @title Create Simulated codeSet
#' 
#' @description
#' Creates a simulated data \code{\link{codeSet}} based off the given parameters
#' 
#' @param length the length of the simulated \code{\link{codeSet}} to be created
#' @param baserate the \code{\link{baserate}} of the simulated \code{\link{codeSet}}
#' @param kappaMin the minimum kappa of the simulated \code{\link{codeSet}}
#' @param kappaMax the maximum kappa of the simulated \code{\link{codeSet}}
#' @param precisionMin the minimum precision of the simulated \code{\link{codeSet}}
#' @param precisionMax the maximum precision of the simulated \code{\link{codeSet}}
#' 
#' @keywords codeSet, create
#' 
#' @details
#' \code{\link{codeSet}}s are generated by first picking a random kappa within its range and a random precision within its range.  If the random kappa, random precision, and baserate are not mathematically possible, then the precision is resampled from a range of mathematically possible values.  A unique simulated \code{\link{codeSet}} is then constructed given these parameters.
#' 
#' @return returns a simulated \code{\link{codeSet}} that fulfills the given parameters
#' 
###

createScS = function(length, baserate, kappaMin, kappaMax, precisionMin, precisionMax){
  return(createRandomSet(setLength = length, baserate = baserate, kappa = runif(1, kappaMin, kappaMax), minPrecision = precisionMin, maxPrecision = precisionMax))
}